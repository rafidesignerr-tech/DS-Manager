/**
 * Generates drizzle/seed/components.sql from app/catalog/components.json so the
 * database rows (search, tasks, changelog links, relations) match the catalog.
 *
 *   npm run components:generate
 *   npm run db:seed:components:local        (or paste the file into the D1 console)
 *
 * Safe to run again after the catalog changes: rows are upserted by id, so
 * links from tasks and changelog entries are kept. Components that left the
 * catalog are removed. Tracking rows are never overwritten; a component whose
 * Figma page is marked /done starts with Design = Done.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

interface Entry {
  id: string;
  title: string;
  level: string;
  category: string;
  summary: string;
  designDone: boolean;
  uses: string[];
}
interface Catalog {
  categories: { key: string; label: string; description: string }[];
  components: Entry[];
}

const catalog = JSON.parse(readFileSync("app/catalog/components.json", "utf8")) as Catalog;
const q = (v: string | number | null) => (v === null ? "NULL" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`);

const ids = catalog.components.map((c) => c.id);
const lines: string[] = [
  "-- Components from the Figma library (generated by scripts/generate-components-seed.ts).",
  "DELETE FROM reference_item WHERE kind = 'component' AND is_sample = 1;",
  `DELETE FROM reference_item WHERE kind = 'component' AND id NOT IN (${ids.map(q).join(", ")});`,
  "DELETE FROM reference_group WHERE kind = 'component';",
];

catalog.categories.forEach((g, i) =>
  lines.push(`INSERT INTO reference_group (kind, key, label, description, sort_order) VALUES ('component', ${q(g.key)}, ${q(g.label)}, ${q(g.description)}, ${i});`),
);

catalog.components.forEach((c, i) => {
  const status = c.designDone ? "beta" : "draft";
  lines.push(
    `INSERT INTO reference_item (id, kind, group_key, title, summary, details, level, status, value, preview_key, is_sample, sort_order) VALUES (${q(c.id)}, 'component', ${q(c.category)}, ${q(c.title)}, ${q(c.summary)}, '', ${q(c.level)}, ${q(status)}, NULL, ${q(c.id)}, 0, ${i}) ` +
      `ON CONFLICT(id) DO UPDATE SET group_key = excluded.group_key, title = excluded.title, summary = excluded.summary, level = excluded.level, status = excluded.status, preview_key = excluded.preview_key, is_sample = 0, sort_order = excluded.sort_order;`,
  );
});

lines.push("DELETE FROM reference_relation WHERE kind = 'uses' AND from_id IN (SELECT id FROM reference_item WHERE kind = 'component');");
let relations = 0;
for (const c of catalog.components) {
  for (const to of c.uses) {
    lines.push(`INSERT INTO reference_relation (from_id, to_id, kind) VALUES (${q(c.id)}, ${q(to)}, 'uses');`);
    relations++;
  }
}

const done = catalog.components.filter((c) => c.designDone);
for (const c of done) lines.push(`INSERT OR IGNORE INTO token_tracking (token_id, design_status) VALUES (${q(c.id)}, 'done');`);

mkdirSync("drizzle/seed", { recursive: true });
writeFileSync("drizzle/seed/components.sql", lines.join("\n") + "\n");
console.log(`Wrote ${catalog.categories.length} categories, ${catalog.components.length} components, ${relations} relations, ${done.length} design-done rows.`);
